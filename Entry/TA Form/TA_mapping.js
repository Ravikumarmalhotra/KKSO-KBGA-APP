// Generates e.g. "January-2026" ... "December-2026" for the CURRENT year
function buildTAMonthsForYear(year) {
  return MONTH_NAMES_FULL.map(m => `${m}-${year}`);
}

// List used in View page dropdown (12 months of current year)
const TAMonths = buildTAMonthsForYear(new Date().getFullYear());

// Returns current month's sheet name, e.g. "June-2026"
function getCurrentTAMonth() {
  const d = new Date();
  return `${MONTH_NAMES_FULL[d.getMonth()]}-${d.getFullYear()}`;
}
